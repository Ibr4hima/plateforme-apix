def libelles_2024(sens: str) -> list[str]:
    ordre: list[str] = []
    for r in csv.DictReader(open(ici.parent / "edition_2024_chapitres.csv", encoding="utf-8")):
        if r["sens"] == sens and r["chapitre"] not in ordre:
            ordre.append(r["chapitre"])
    return ordre

