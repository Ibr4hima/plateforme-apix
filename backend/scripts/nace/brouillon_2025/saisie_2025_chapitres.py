def ecrire() -> None:
    """Écrit edition_2025_chapitres.csv et edition_2025_totaux_chapitres.csv."""
    tables = {"export": (EXPORT_VALEUR, EXPORT_POIDS), "import": (IMPORT_VALEUR, IMPORT_POIDS)}
    totaux = {"export": (EXPORT_VALEUR_TOTAL, EXPORT_POIDS_TOTAL),
              "import": (IMPORT_VALEUR_TOTAL, IMPORT_POIDS_TOTAL)}
    with open(ici / f"edition_{EDITION}_chapitres.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["chapitre", "sens", "annee", "valeur", "poids", "edition"])
        for sens, (val, pds) in tables.items():
            lib = libelles_2024(sens)
            assert len(lib) == len(val) == len(pds) == 96, sens
            for c, v, p in zip(lib, val, pds):
                for i, an in enumerate(ANNEES):
                    w.writerow([c, sens, an, "" if v[i] is None else v[i],
                                "" if p[i] is None else p[i], EDITION])
    with open(ici / f"edition_{EDITION}_totaux_chapitres.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["sens", "mesure", "annee", "total", "edition"])
        for sens, (tv, tp) in totaux.items():
            for mesure, tot in (("valeur", tv), ("poids", tp)):
                for i, an in enumerate(ANNEES):
                    w.writerow([sens, mesure, an, tot[i], EDITION])
    print("96 chapitres × 2 sens × 5 ans écrits.")


if __name__ == "__main__":
    ecrire()
